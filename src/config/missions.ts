export interface MissionDef {
  id: string;
  title: string;
  desc: string;
  /** Prime en centimes. */
  money: number;
  xp: number;
  progress: (s: GameState) => { cur: number; target: number };
  hint?: string;
}

const count = (cur: number, target: number) => ({ cur: Math.min(cur, target), target });
const coopsAtLevel = (s: GameState, lvl: number) => s.buildings.filter((b) => b.type === 'coop' && b.level >= lvl).length;
